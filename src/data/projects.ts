const wp = (
  projectId: string,
  n: number,
  name: string,
  ps: string,
  pf: string,
  as: string | null,
  ff: string,
  progress: number,
  planned: number,
  owner: string,
  extra: Partial<WorkPackage> = {},
): WorkPackage => {
  const variance = progress - planned
  return {
    id: `${projectId}-WP${String(n).padStart(2, '0')}`,
    projectId,
    status: progress >= 100 ? 'Completed' : progress === 0 ? 'Not Started' : variance <= -5 ? 'Delayed' : variance < 0 ? 'At Risk' : 'On Track',
    owner,
    createdAt: '2025-11-15',
    updatedAt: '2026-10-01',
    name,
    plannedStart: ps,
    plannedFinish: pf,
    actualStart: as,
    forecastFinish: ff,
    progress,
    planned,
    ...extra,
  }
}

