const genericPackages: Record<string, string[]> = {
  Construction: ['Civil & Foundations', 'Structural Steel', 'Mechanical Erection', 'Piping Fabrication', 'Piping Installation', 'Electrical & Instrumentation', 'Insulation & Painting', 'Pre-commissioning'],
  'O&M': ['Preventive Maintenance', 'Corrective Maintenance', 'Shutdown Planning', 'Condition Monitoring', 'Spares Management'],
}

projects
  .filter((p) => p.id !== 'NPE')
  .forEach((p) => {
    const names = genericPackages[p.type]
    names.forEach((name, i) => {
      const spread = (i - names.length / 2) * 7
      const planned = Math.max(0, Math.min(100, Math.round(p.planned + spread)))
      const slip = p.progress - p.planned
      const progress = Math.max(0, Math.min(100, Math.round(planned + slip + (i % 3 === 0 ? -2 : 1))))
      workPackages.push(
        wp(p.id, i + 1, name, p.startDate, p.finishDate, progress > 0 ? p.startDate : null, p.finishDate, progress, planned, p.manager,
          progress - planned <= -5
            ? { delayCause: i % 2 ? 'Late vendor drawings' : 'Permit-to-work turnaround', affected: `${4 + i} work fronts`, action: 'Recovery plan and look-ahead review', actionOwner: 'Project Manager', impactDays: 2 + (i % 3) }
            : {}),
      )
    })
  })

